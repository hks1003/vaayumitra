"""
Write latex/numbers.tex: every number printed on the LaTeX poster as a macro, computed from results/
(same sources as make_poster.py), and copy the figures the poster uses into latex/figs/.
Re-run after any pipeline change, then recompile poster.tex.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).parent))
import make_poster as V1  # noqa: E402

RES, FIG, TEX = ROOT / "results", ROOT / "figures", ROOT / "latex"
FIGS = ["F1_monthly_saving.png", "F3_shap.png", "F4_parity.png", "F5_coast_map.png", "F6_sensitivity.png",
        "F7_wind_bins.png", "F8_validation.png", "app_screenshot.png", "qr_app.png",
        "paper_imgs/ind17_sail_bw.png", "paper_imgs/ind18_sail_bw.png",
        "photos/photo1.jpg", "photos/photo2.jpg", "photos/photo3.jpg"]


def main():
    N = V1.numbers()
    A, B, nat, ml = N["A"], N["B"], N["nat"], N["ml"]
    a6 = A.loc[("frp", 6.0)]
    live = json.loads((RES / "live_example.json").read_text())
    harb = N["harb"]
    m = {
        "NTrips": f"{N['n_trips']:,}", "Span": N["span"].replace("–", "--"),
        "Rsq": f"{ml['mlp_ensemble']['r2']:.3f}", "MAE": f"{ml['mlp_ensemble']['mae_L']:.2f}",
        "Qband": f"{ml['conformal_q90_L']:.1f}", "Cover": f"{100 * ml['conformal_coverage_test']:.0f}",
        "Payback": f"{a6.payback_months:.0f}", "InrBoat": f"{nat['sail_only_inr_per_boat_yr'] / 1e3:.0f}",
        "LakhPkg": f"{B.loc['frp', 'inr_yr'] / 1e5:.1f}", "MLdiesel": f"{nat['india']['ML_diesel']:.0f}",
        "Crore": f"{nat['india']['crore']:.0f}", "Ktco": f"{nat['india']['kt_co2']:.0f}",
        "Craft": f"{nat['india']['craft']:,}", "East": f"{N['east']:.0f}", "West": f"{N['west']:.0f}",
        "Tip": f"{N['tip']:.0f}", "NCell": f"{N['ncell']}",
        "APcr": f"{nat['Andhra Pradesh']['crore']:.0f}", "KLcr": f"{nat['Kerala']['crore']:.0f}",
        "Kochi": f"{harb['Kochi']:.0f}", "Chennai": f"{harb['Chennai']:.0f}",
        "Vizag": f"{harb['Visakhapatnam']:.0f}", "BestPct": f"{N['best_pct']:.0f}", "BestMonth": N["best_m"],
        "PkgBefore": f"{B.loc['frp', 'fuel_before_L']:.0f}", "PkgAfter": f"{B.loc['frp', 'fuel_after_L']:.0f}",
        "PkgPct": f"{B.loc['frp', 'save_pct']:.0f}",
        "LiveDay": __import__("datetime").date.fromisoformat(live["day"]).strftime("%d %b %Y"),
        "HabitFuel": f"{live['habit']['fuel']:.1f}", "HabitTrip": f"{live['habit']['trip_h']:.1f}",
        "SailFuel": f"{live['sail_only']['fuel']:.1f}", "SailHours": f"{live['sail_only']['sail']:.1f}",
        "BestDep": f"{live['best']['dep']:02d}:00", "BestSpeed": f"{live['best']['speed']}",
        "BestSail": f"{live['best']['sail']:.1f}", "BestFuel": f"{live['best']['fuel']:.1f}",
        "BestTrip": f"{live['best']['trip_h']:.1f}", "BestWind": f"{live['best']['wind']:.1f}",
        "BestHs": f"{live['best']['hs']:.1f}",
        "BestSaveL": f"{live['habit']['fuel'] - live['best']['fuel']:.1f}",
        "BestSaveRs": f"{100 * (live['habit']['fuel'] - live['best']['fuel']):,.0f}",
        "BestSavePct": f"{100 * (1 - live['best']['fuel'] / live['habit']['fuel']):.0f}",
    }
    # ---- feasibility: does the sail still pay at the savings measured in past trials? ----
    import pandas as pd
    base_L = float(a6.fuel_before_L)                       # FRP boat, 6 kn, fuel per trip without sail
    pay = lambda pct, kit=12_000, days=200, price=100.0: 12 * kit / (base_L * pct / 100 * days * price)
    sens = pd.read_csv(RES / "sensitivity.csv")
    L_low = float(sens[(sens.knob.str.startswith("Sail area")) & (sens.side == "low")].L.iloc[0])
    worst = 12 * 20_000 / (L_low * 150 * 90)                # every adverse case at once
    m.update({"BaseL": f"{base_L:.1f}", "PayAtSix": f"{pay(6):.0f}", "PayAtTen": f"{pay(10):.0f}",
              "InrAtSix": f"{base_L * 0.06 * 200 * 100 / 1e3:.0f}", "PayWorst": f"{worst:.0f}",
              "PayMin": f"{sens.payback_m.min():.1f}", "PayMax": f"{sens.payback_m.max():.1f}"})
    lines = ["% auto-generated by src/make_latex_numbers.py -- do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    TEX.mkdir(exist_ok=True)
    (TEX / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (TEX / "figs").mkdir(exist_ok=True)
    for f in FIGS:
        shutil.copy(FIG / f, TEX / "figs" / Path(f).name)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
